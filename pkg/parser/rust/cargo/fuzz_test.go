package cargo

import (
	"bytes"
	"context"
	"os"
	"path/filepath"
	"testing"

	xio "github.com/khulnasoft/dep-parser/pkg/x/io"
)

// FuzzParse exercises the Cargo.lock parser against arbitrary input.
// Run with: go test -fuzz=FuzzParse -fuzztime=30s ./pkg/parser/rust/cargo/
func FuzzParse(f *testing.F) {
	matches, err := filepath.Glob("testdata/*")
	if err == nil {
		for _, m := range matches {
			if data, err := os.ReadFile(m); err == nil {
				f.Add(data)
			}
		}
	}
	f.Add([]byte("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"a\"\nversion = \"0.1.0\"\n"))
	f.Add([]byte(""))

	f.Fuzz(func(t *testing.T, data []byte) {
		rsa, err := xio.NewReadSeekerAt(bytes.NewReader(data))
		if err != nil {
			t.Skip(err)
		}
		_, _, _ = NewParser().Parse(context.Background(), rsa)
	})
}
