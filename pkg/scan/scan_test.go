package scan

import (
	"context"
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
	require.NoError(t, os.WriteFile(path, []byte(content), 0o644))
}

func TestScanEmptyDir(t *testing.T) {
	rep, err := Scan(context.Background(), t.TempDir(), Options{})
	require.NoError(t, err)
	assert.Empty(t, rep.Results)
	assert.Empty(t, rep.Errors)
}

func TestScanMissingDir(t *testing.T) {
	_, err := Scan(context.Background(), "/nonexistent/dir/xyz", Options{})
	require.Error(t, err)
}

func TestScanFindsLockfiles(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "go.mod"), "module example.com/x\n\ngo 1.21\n")
	writeFile(t, filepath.Join(dir, "sub", "poetry.lock"), `# This file is automatically @generated by Poetry and should not be changed by hand.

[[package]]
name = "certifi"
version = "2024.1.1"
description = "Python package for providing Mozilla's CA Bundle."
optional = false
python-versions = ">=3.6"
`)
	writeFile(t, filepath.Join(dir, "notes.txt"), "nothing here")

	rep, err := Scan(context.Background(), dir, Options{})
	require.NoError(t, err)
	require.Len(t, rep.Results, 2)
	assert.Empty(t, rep.Errors)

	byParser := map[string]int{}
	for _, r := range rep.Results {
		byParser[r.Parser]++
		assert.NotEmpty(t, r.Packages)
	}
	assert.Equal(t, 1, byParser["golang-mod"])
	assert.Equal(t, 1, byParser["python-poetry"])
}

func TestScanExcludesDirs(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "node_modules", "dep", "package.json"), `{"name":"dep","version":"1.0.0"}`)
	writeFile(t, filepath.Join(dir, "package.json"), `{"name":"root","version":"1.0.0"}`)

	rep, err := Scan(context.Background(), dir, Options{})
	require.NoError(t, err)
	// node_modules excluded by default; only root package.json parsed
	require.Len(t, rep.Results, 1)
	assert.Equal(t, "nodejs-pkg", rep.Results[0].Parser)
}

func TestScanCollectsErrors(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "package-lock.json"), "{corrupt json")

	rep, err := Scan(context.Background(), dir, Options{})
	require.NoError(t, err)
	assert.Empty(t, rep.Results)
	require.Len(t, rep.Errors, 1)
	assert.Equal(t, "nodejs-npm", rep.Errors[0].Parser)
}

func TestScanRespectsContextCancel(t *testing.T) {
	dir := t.TempDir()
	for i := 0; i < 50; i++ {
		writeFile(t, filepath.Join(dir, "f"+string(rune('a'+i%26))+string(rune('0'+i/26))+".txt"), "x")
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	_, err := Scan(ctx, dir, Options{})
	require.Error(t, err)
}

func TestAllPackagesAndDeps(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "go.mod"), "module example.com/x\n\ngo 1.21\nrequire github.com/sirupsen/logrus v1.9.0\n")

	rep, err := Scan(context.Background(), dir, Options{})
	require.NoError(t, err)
	assert.NotEmpty(t, rep.AllPackages())
}

func TestSummary(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "go.mod"), "module example.com/x\n")
	rep, err := Scan(context.Background(), dir, Options{})
	require.NoError(t, err)
	assert.Contains(t, rep.Summary(), "golang-mod")
}
